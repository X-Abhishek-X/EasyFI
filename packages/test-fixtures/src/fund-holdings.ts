// Top-N fund constituents (approximate, as of the 2026-06-30 N-PORT snapshot) plus full-fund
// sector weights. Weights are written in percent for readability and converted to fractions.
// Alphabet's two share classes are combined under GOOGL.
import { CD, CS, COMM, EN, FIN, HC, IND, IT, MAT, RE, UT, security } from './securities';

export interface FixtureFundConstituent {
  fundTicker: string;
  constituentTicker: string | null;
  name: string;
  weight: number;
  assetBucket: 'stocks' | 'bonds' | 'cash' | 'commodities' | 'crypto' | 'other';
  sector: string | null;
  industry: string | null;
}

export interface FixtureFundSnapshot {
  asOf: string;
  constituents: FixtureFundConstituent[];
  sectorWeights?: Record<string, number>;
}

export const HOLDINGS_AS_OF = '2026-06-30';

type Row = [ticker: string, weightPct: number];
type UnmappedRow = { name: string; weightPct: number; assetBucket: 'cash' | 'other' | 'bonds' };

const pct = (n: number): number => Math.round(n * 1e4) / 1e6;

function book(
  fund: string,
  rows: Row[],
  sectorWeights: Record<string, number>,
  unmapped: UnmappedRow[] = [],
): FixtureFundSnapshot {
  const constituents: FixtureFundConstituent[] = rows.map(([ticker, w]) => {
    const s = security(ticker);
    return {
      fundTicker: fund,
      constituentTicker: ticker,
      name: s.name,
      weight: pct(w),
      assetBucket: 'stocks',
      sector: s.sector,
      industry: s.industry,
    };
  });
  for (const u of unmapped) {
    constituents.push({
      fundTicker: fund,
      constituentTicker: null,
      name: u.name,
      weight: pct(u.weightPct),
      assetBucket: u.assetBucket,
      sector: null,
      industry: null,
    });
  }
  return { asOf: HOLDINGS_AS_OF, constituents, sectorWeights };
}

function relabel(fund: string, snap: FixtureFundSnapshot): FixtureFundSnapshot {
  return {
    ...snap,
    sectorWeights: { ...snap.sectorWeights },
    constituents: snap.constituents.map((c) => ({ ...c, fundTicker: fund })),
  };
}

